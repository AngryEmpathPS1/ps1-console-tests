/*
 * cpu/refresh-pair - where a second access behind a load sits on the bus in cold code: refresh-cold's map for every cell of the
 * second-access grid (2026-10-31)
 *
 * WHY. load-fill5 / load-fill6's grid, the extra a second access costs behind a stream load, by the load's word and the distance,
 * reads on the consoles 2 3 0 / 1 0 0 / 2 4 4 / 2 4 3 over 8.23 (a load) and 9.29 (a store) and on this core 3 2 1 / 1 1 0 / 1 4 4 /
 * 3 4 2 (STATUS v0.377.230). A table on the wait fits those cells and takes the corpus nowhere (experiments/_mkktab231.js: loads
 * 0.897, stores 1.083 against 0.898), so the cost of a cell does not say why. A cost is a sum. The refresh is a stopwatch: where it
 * comes due inside a block says which access held the bus at that cycle, so the map of a cell is its order on the bus.
 *
 * WHAT IT DOES. refresh-cold's sweep, unchanged: interrupts off, Timer 2 at the system clock, the same calibration, a block of 20
 * cache lines with what the case puts in its line 8, each block in its own 512-byte slot, evicted before every trial, 16 trials at
 * each of the 256 phases, the sweep itself warm.
 *   N        nops only
 *   Lw       lw RAM at word w of line 8
 *   LLw+d    lw RAM at word w, a second lw RAM d instructions on, one page, another register
 *   LSw+d    lw RAM at word w, a sw RAM d instructions on
 * w + d past 3 puts the second access in line 9, behind that line's fill.
 *
 * READ IT LIKE THIS. As refresh-cold: x is how many cycles into the block the refresh comes due. A row's cells minus its commonest
 * are what the refresh costs there, flat outside the block. Near x = 72 they step where one bus user gives way to the next.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: `node hwtests/run.js refresh-pair --frames=14000 --quiet=900`.
 */
