typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { sm2B0_trial, sm2B1_trial, sm2B2_trial, sm2B3_trial, sm2B4_trial, sm2B5_trial, sm2B6_trial, sm2B7_trial };
static const char* const names[] = {
    "J0  jal to word 0 of C",
    "J1  jal to word 1 of C",
    "J2  jal to word 2 of C",
    "J3  jal to word 3 of C",
    "S   fall from warm W (entered at word 0) into C",
    "S3  fall from warm W (entered at word 3) into C",
    "WC  W and C both cold, entered at W word 0",
    "JD  jal to word 0 of C, D after it cold too"
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);                               /* the evictors' own lines warm */
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

