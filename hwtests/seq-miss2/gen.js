'use strict';
// Writes hwtests/seq-miss2/main.cpp: node hwtests/seq-miss2/gen.js
const fs = require('fs'), path = require('path');
// [name, label, entry label, evict W too]
const CASES = [
  ['J0', 'jal to word 0 of C', 'c0', 0],
  ['J1', 'jal to word 1 of C', 'c1', 0],
  ['J2', 'jal to word 2 of C', 'c2', 0],
  ['J3', 'jal to word 3 of C', 'c3', 0],
  ['S', 'fall from warm W (entered at word 0) into C', 'w0', 0],
  ['S3', 'fall from warm W (entered at word 3) into C', 'w3', 0],
  ['WC', 'W and C both cold, entered at W word 0', 'w0', 1],
  ['JD', 'jal to word 0 of C, D after it cold too', 'c0', 2],
];
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , tgt, ev2], i) => {
  const b = 'sm2B' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  // the whole trial here, so nothing but the evicted line(s) is cold in the timed pass:
  // a0 = evict?, a1 = spin turns; t9 = 1F800000h; returns the count in v0
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`jal ${b}_entry`) + q('nop');
  asm += q(`beqz $a0, ${b}_sp`) + q('nop') + q(`jal ${b}_ev`) + q('nop');
  if (ev2 === 1) asm += q(`jal ${b}_evw`) + q('nop');
  if (ev2 === 2) asm += q(`jal ${b}_evd`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  // w16 / r16 at +0x80 / +0x90
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  // the entry at +0x100 (ra kept in t8)
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_${tgt}`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  // W at +0x1F0, C at +0x200, D at +0x210
  asm += q(`.org ${b}_trial + 0x1F0`);
  asm += q(`${b}_w0:`) + q('nop') + q('nop') + q('nop') + q(`${b}_w3:`) + q('nop');
  asm += q(`${b}_c0:`) + q('nop') + q(`${b}_c1:`) + q('nop') + q(`${b}_c2:`) + q('nop') + q(`${b}_c3:`) + q('nop');
  asm += q(`${b}_d:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
  // the evictors 4 KB above: C's index, W's, D's
  asm += q(`.org ${b}_trial + 0x11F0`) + q(`${b}_evw:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
  asm += q(`${b}_ev:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
  asm += q(`${b}_evd:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t sm2B${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `sm2B${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '   ').slice(0, 3)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '    ').slice(0, 4)}${w}`).join('\n');

const src = `/*
 * cpu/seq-miss2 - seq-miss with the whole trial in each slot's own code: a cold line entered by a jump or by falling
 * through, with NOTHING else cold in the timed pass (2026-10-12 small hours)
 *
 * WHY. hwtests/seq-miss on the SCPH-1001 (three runs, identical): a miss 5 cycles at every entry word (here 4 3 3 4). But
 * its trials ran from C, and the C code between the warm-up pass and the timed one shares cache lines with the slot's
 * read stub and entry line: in the timed pass those missed too (this core's trace), so its "warm" rows were not, and
 * the read stub's own miss read as here on the console while C's read a cycle over. Here the warm-up pass, the evictor
 * call, the spin and the timed pass are all one routine in the slot, so the timed pass meets only the evicted line(s).
 *
 * WHAT IT DOES. Interrupts off, Timer 2 at the system clock. Each case its own 8 KB slot: the trial routine (+0), warm
 * stubs that reset and read the counter (+80h, +90h), the entry (+100h), and W, C, D (+1F0h, +200h, +210h: D is jr ra);
 * evictors 4 KB above at C's, W's and D's index. 16 trials a case, the spin moving each by 16 cycles; cold (the
 * evictor(s) called) against warm (not):
${caseList}
 *
 * READ IT LIKE THIS. cold - warm is the miss's cost with nothing else cold. J0 against S: the same line entered by a jump
 * or by falling through; WC and JD: two misses back to back.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js seq-miss2\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);                               /* the evictors' own lines warm */
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/seq-miss2\\n");
    printf("A cold line by a jump or a fall-through, nothing else cold (Timer 2 cycles, fastest..slowest of 16; cold / warm).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span c = run(trials[i], 1), w = run(trials[i], 0);
        printf("  %-46s cold %3u..%-3u  warm %3u..%-3u  miss %d\\n", names[i], (unsigned)c.lo, (unsigned)c.hi, (unsigned)w.lo, (unsigned)w.hi, (int)c.lo - (int)w.lo);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
