'use strict';
// Writes hwtests/sw-ioread4/main.cpp: node hwtests/sw-ioread4/gen.js
const fs = require('fs'), path = require('path');
// All warm. What waits behind a JOY_STAT read that waits for the write queue: a RAM store (or none), the read (its value
// never read), k nops, then the NEXT access - a RAM load, a second JOY_STAT read, or a BIOS ROM load (each into its own
// register, never read either).
const NEXT = {
  M: ['lw $t4, 0x44($t6)', 'RAM lw'],
  J: ['lbu $t4, 0x1044($t9)', 'JOY_STAT lbu'],
  O: ['lw $t4, 0($t5)', 'ROM lw'],
  X: ['nop', 'nothing'],
};
// sw-ioread4: the stores further back. Three words of stores: N none; R one RAM sw (last); P two, sw; nop; sw (one 1 KB
// block - bios-window's sw; jal; sw before its bracket). Then g nops, the JOY_STAT lbu, and the next access: a ROM lw in
// the read's delay slot (O0) or a RAM lw 2 nops on (M2).
const PRE = { N: ['nop', 'nop', 'nop'], R: ['nop', 'nop', 'sw $t1, 0x40($t6)'], P: ['sw $t1, 0x40($t6)', 'nop', 'sw $t1, 0x44($t6)'] };
const WHAT = { N: 'no store', R: 'RAM sw', P: 'sw;nop;sw' };
const CASES = [];
for (const [nk, k] of [['O', 0], ['M', 2]]) for (const sk of ['N', 'R', 'P']) for (const g of [0, 1, 2, 3, 4]) {
  const words = [...PRE[sk]];
  for (let j = 0; j < g; j++) words.push('nop');
  words.push('lbu $t0, 0x1044($t9)');
  for (let j = 0; j < k; j++) words.push('nop');
  words.push(NEXT[nk][0]);
  CASES.push([`${sk}${g}${nk}${k}`, `${WHAT[sk]}, ${g} nop${g === 1 ? '' : 's'}, JOY_STAT lbu, ${k} nops, ${NEXT[nk][1]}`, words]);
}
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw], i) => {
  const b = 's4B' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q('lui $t5, 0xbfc0') + q(`la $t6, ${b}_trial`) + q('lw $t1, 0x40($t6)');
  asm += q(`jal ${b}_entry`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_c`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  asm += q(`.org ${b}_trial + 0x200`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  asm += q('nop') + q('nop') + q('nop') + q('nop') + q('nop') + q('nop') + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t s4B${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `s4B${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '     ').slice(0, 5)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '      ').slice(0, 6)}${w}`).join('\n');

const src = `/*
 * cpu/sw-ioread4 - the next access behind an on-die read, with the stores further back (2026-10-12)
 *
 * WHY. hwtests/sw-ioread3 (SCPH-1001 x3): with a RAM store right before a JOY_STAT read, the next access pays 2 at 0-3
 * nops behind the read and 1 at 4 - the read's lateness, as a reader of its value pays it. But hwtests/bios-window, whose
 * Timer 2 read comes three instructions after two stores (sw; jal; sw), needs its next access (a ROM lw in the read's
 * delay slot) a whole cycle late where this core's queue says the read waits only 1 - and counter-bracket says the read
 * samples after that whole wait. Here the stores 0-4 nops further back, one store or bios-window's two, and the next
 * access in the read's delay slot (a ROM lw) or 2 nops on (a RAM lw); no loaded value is ever read.
 *
 * WHAT IT DOES. All warm, sw-ioread's harness. 16 trials over the refresh:
${caseList}
 *
 * READ IT LIKE THIS. R or P against N at the same g and next access: what the stores cost the next access, by how far
 * back they are.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js sw-ioread4\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t) {
    Span s = { 0xFFFF, 0 };
    t(0, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(0, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/sw-ioread4\\n");
    printf("The next access behind an on-die read, the stores further back, warm code (Timer 2 cycles, fastest..slowest of 16).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span w = run(trials[i]);
        printf("  %-58s cold %3u..%-3u  warm %3u..%-3u  miss 0\\n", names[i], (unsigned)w.lo, (unsigned)w.hi, (unsigned)w.lo, (unsigned)w.hi);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp, ' + CASES.length + ' cases');
