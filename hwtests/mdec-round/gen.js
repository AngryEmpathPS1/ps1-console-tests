'use strict';
/*
 * hwtests/mdec-round/gen.js - chooses the test's blocks and writes blocks.h.
 *
 * At q_scale 0 every coefficient is its level x 32 in this core's units (x2
 * in psx-spx's), exactly, so three IDCT rules differ only in how they round:
 *   A  this core since M224: pass 1 carried at full precision, rounded once
 *   B  each pass rounded to nearest (>> 18) and cut to s16 between (DuckStation;
 *      this core before M224)
 *   C  pass 1 carried, FLOORED once (MiSTer's rtl/mdec.vhd)
 * The layout is the core's (src/psx.js MDEC): the scale table and the zigzag
 * order are both transposed. Two controls where all three agree, four flat
 * blocks where A parts from B, and ten DC + one AC blocks where each rule
 * parts from both others. The predictions are checked by running the test on
 * the core with its idct() swapped for each rule (STATUS, hwtests/mdec-round).
 *
 *   node hwtests/mdec-round/gen.js
 */
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', '..', 'src', 'psx.js'), 'utf8');
const ZZ = Uint8Array.from(src.match(/const MDEC_ZAGZIG = new Uint8Array\(\[([^\]]+)\]/)[1].split(',').map((s) => +s.trim()).filter((x) => !isNaN(x)));
const ZZT = ZZ.map((i) => ((i & 7) << 3) | (i >>> 3));
// ps1-tests common/mdec.cpp's idct[] - the table the test uploads.
const IDCT = [23170, 23170, 23170, 23170, 23170, 23170, 23170, 23170, 32138, 27245, 18204, 6392, -6393, -18205, -27246, -32139, 30273, 12539, -12540, -30274, -30274, -12540, 12539, 30273, 27245, -6393, -32139, -18205, 18204, 32138, 6392, -27246, 23170, -23171, -23171, 23170, 23170, -23171, -23171, 23170, 18204, -32139, 6392, 27245, -27246, -6393, 32138, -18205, 12539, -30274, 30273, -12540, -12540, 30273, -30274, 12539, 6392, -18205, 27245, -32139, 32138, -27246, 18204, -6393];
const st = new Int16Array(64);
for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) st[y * 8 + x] = IDCT[x * 8 + y];
const clamp = (v) => (v < -128 ? -128 : v > 127 ? 127 : v);

function carried(blk, round) {
  const tmp = new Float64Array(64), out = new Int16Array(64);
  for (let x = 0; x < 8; x++) for (let y = 0; y < 8; y++) { let s = 0; for (let i = 0; i < 8; i++) s += blk[x * 8 + i] * st[y * 8 + i]; tmp[y * 8 + x] = s; }
  for (let x = 0; x < 8; x++) for (let y = 0; y < 8; y++) {
    let s = 0; for (let i = 0; i < 8; i++) s += tmp[x * 8 + i] * st[y * 8 + i];
    out[x * 8 + y] = clamp(Math.floor((s + (round ? 34359738368 : 0)) / 68719476736));
  }
  return out;
}
function perPass(blk) {
  const tmp = new Int16Array(64), out = new Int16Array(64);
  const row = (a, off, m) => { let s = 0; for (let i = 0; i < 8; i++) s += a[off + i] * st[m + i]; return (Math.floor((s + 0x20000) / 262144) << 16) >> 16; };
  for (let x = 0; x < 8; x++) for (let y = 0; y < 8; y++) tmp[y * 8 + x] = row(blk, x * 8, y * 8);
  for (let x = 0; x < 8; x++) for (let y = 0; y < 8; y++) out[x * 8 + y] = clamp(row(tmp, x * 8, y * 8));
  return out;
}
const rules = { A: (b) => carried(b, true), B: perPass, C: (b) => carried(b, false) };
function block(dc, k, v) {
  const blk = new Int16Array(64);
  blk[ZZT[0]] = dc * 32;
  if (k) blk[ZZT[k]] = v * 32;
  return blk;
}
const diff = (a, b) => { let n = 0; for (let i = 0; i < 64; i++) if (a[i] !== b[i]) n++; return n; };
const outOf = (dc, k, v) => { const o = {}; for (const r of ['A', 'B', 'C']) o[r] = rules[r](block(dc, k, v)); return o; };
const sat = (o) => ['A', 'B', 'C'].some((r) => o[r].some((x) => x === 127 || x === -128));

const pick = [];
for (const dc of [0, 64, -192, 256]) { const o = outOf(dc, 0, 0); if (!diff(o.A, o.B) && !diff(o.A, o.C) && !sat(o)) pick.push({ dc, k: 0, v: 0, o, role: 'control' }); if (pick.length === 2) break; }
const dcs = [];
for (let dc = -400; dc <= 400; dc++) { const o = outOf(dc, 0, 0); if (!sat(o) && diff(o.A, o.B)) dcs.push({ dc, k: 0, v: 0, o, role: 'DC' }); }
for (const i of [0, Math.floor(dcs.length / 3), Math.floor(2 * dcs.length / 3), dcs.length - 1]) pick.push(dcs[i]);
const acs = [];
for (const k of [1, 2, 3, 5, 9, 14, 20, 27, 35, 44, 54, 63]) {
  let best = null;
  for (let dc = -100; dc <= 100; dc += 5) for (let v = -300; v <= 300; v += 3) {
    const o = outOf(dc, k, v);
    if (sat(o)) continue;
    const s = Math.min(diff(o.A, o.B), diff(o.A, o.C), diff(o.B, o.C));
    if (!best || s > best.s) best = { dc, k, v, o, s, role: 'AC' };
  }
  if (best && best.s > 0) acs.push(best);
}
pick.push(...acs.slice(0, 10));

const hw = (x) => '0x' + (x & 0xFFFF).toString(16).padStart(4, '0');
const bytes = (arr) => Array.from(arr, (x) => (x + 128) & 0xFF).join(',');
const lines = ['/* Generated by hwtests/mdec-round/gen.js - see main.cpp. */', `#define NBLOCKS ${pick.length}`,
  'struct Block { const char* role; int16_t dc, k, v; uint16_t words; uint16_t rle[4]; uint8_t a[64], b[64], c[64]; };',
  'static const Block blocks[NBLOCKS] = {'];
for (const p of pick) {
  const rle = [p.dc & 0x3FF];
  if (p.k) rle.push((((p.k - 1) & 0x3F) << 10) | (p.v & 0x3FF));
  rle.push(0xFE00);                                // end of block
  if (rle.length & 1) rle.push(0xFE00);            // the word's other half: no padding WORDS (STATUS M236)
  const words = rle.length / 2;
  while (rle.length < 4) rle.push(0);
  lines.push(`  { "${p.role}", ${p.dc}, ${p.k}, ${p.v}, ${words}, { ${rle.map(hw).join(', ')} },`);
  lines.push(`    { ${bytes(p.o.A)} },`, `    { ${bytes(p.o.B)} },`, `    { ${bytes(p.o.C)} } },`);
}
lines.push('};');
fs.writeFileSync(path.join(__dirname, 'blocks.h'), lines.join('\n') + '\n');
for (const p of pick) console.log(`${p.role.padEnd(7)} dc ${String(p.dc).padStart(4)} AC ${String(p.k).padStart(2)} = ${String(p.v).padStart(4)}   A/B ${diff(p.o.A, p.o.B)}  A/C ${diff(p.o.A, p.o.C)}  B/C ${diff(p.o.B, p.o.C)}`);
