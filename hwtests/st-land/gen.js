'use strict';
// Writes hwtests/st-land/main.cpp: node hwtests/st-land/gen.js
const fs = require('fs'), path = require('path');
// t9 = 1F800000h. C (entered at word 0 by a jal) holds the Timer 2 counter reset (START) and runs into warm D; the
// closing read is the warm stub's. The count says where START landed against the code after it.
const START = 'sh $zero, 0x1120($t9)';
const CASES = [];
for (let w = 0; w < 4; w++)
  CASES.push([`W${w}`, `START at C word ${w}, nops`, [0, 1, 2, 3].map((k) => (k === w ? START : 'nop'))]);
CASES.push(['L2', 'JOY_STAT lbu at word 1, START at word 2', ['nop', 'lbu $t0, 0x1044($t9)', START, 'nop']]);
CASES.push(['L3', 'JOY_STAT lbu at word 1, START at word 3', ['nop', 'lbu $t0, 0x1044($t9)', 'nop', START]]);
CASES.push(['M', 'cold-bracket\'s: mode read, mode write, mode read, START', ['lhu $t1, 0x1124($t9)', 'sh $zero, 0x1124($t9)', 'lhu $t1, 0x1124($t9)', START]]);
CASES.push(['MA', 'mode read, mode write, mode read, andi, then START at the next line\'s word 0', ['lhu $t1, 0x1124($t9)', 'sh $zero, 0x1124($t9)', 'lhu $t1, 0x1124($t9)', 'andi $t1, $t1, 0xffff'], [START]]);
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw, dw], i) => {
  const b = 'slB' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  // a0 = evict?, a1 = spin turns; t9 = 1F800000h; the count in v0 - the whole trial here
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`jal ${b}_entry`) + q('nop');
  asm += q(`beqz $a0, ${b}_sp`) + q('nop') + q(`jal ${b}_ev`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q('nop') + q('nop');
  asm += q(`jal ${b}_c`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  // C at +0x200, D at +0x210 (warm: what dw holds, then nops and jr ra)
  asm += q(`.org ${b}_trial + 0x200`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  for (const w of (dw || [])) asm += q(w);
  asm += q('nop') + q('nop') + q('nop') + q('nop') + q('jr $ra') + q('nop') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x1200`) + q(`${b}_ev:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t slB${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `slB${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '    ').slice(0, 4)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '     ').slice(0, 5)}${w}`).join('\n');

const src = `/*
 * cpu/st-land - where a Timer 2 counter reset written from a cold line lands, against the code after it (2026-10-12)
 *
 * WHY. hwtests/fix-shadow3 (SCPH-1001 x3): a load in a streaming line costs its own 2 cycles in every shape, cold-bracket's
 * loop shape too - but cold-bracket's own joy100 rows at w0 and w3 read 3-4 under a core that pays them. Its window
 * opens with the counter reset written from inside the cold block (fix-shadow3's from a warm stub): a store this core
 * holds in the stream and writes at its bus moment. If the consoles land it later, the window reads short by as much.
 *
 * WHAT IT DOES. fix-shadow's harness, the trial's own START: C (entered at word 0 by a jal) holds the counter reset at
 * word 0..3; behind a JOY_STAT load at word 1; and cold-bracket's own sequence (mode read, mode write, mode read, START;
 * and with its andi, START at the next line). C runs into warm code, the closing read is a warm stub's. 16 trials over
 * the refresh, cold against warm:
${caseList}
 *
 * READ IT LIKE THIS. cold - warm: negative where START lands later in cold code than in warm (the window shorter).
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js st-land\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/st-land\\n");
    printf("A Timer 2 counter reset written from a cold line (Timer 2 cycles, fastest..slowest of 16; cold / warm).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span c = run(trials[i], 1), w = run(trials[i], 0);
        printf("  %-66s cold %3u..%-3u  warm %3u..%-3u  miss %d\\n", names[i], (unsigned)c.lo, (unsigned)c.hi, (unsigned)w.lo, (unsigned)w.hi, (int)c.lo - (int)w.lo);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
