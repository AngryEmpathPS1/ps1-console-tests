static const char* const names[] = {
    "W0   START at C word 0, nops",
    "W1   START at C word 1, nops",
    "W2   START at C word 2, nops",
    "W3   START at C word 3, nops",
    "L2   JOY_STAT lbu at word 1, START at word 2",
    "L3   JOY_STAT lbu at word 1, START at word 3",
    "M    cold-bracket's: mode read, mode write, mode read, START",
    "MA   mode read, mode write, mode read, andi, then START at the next line's word 0"
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

