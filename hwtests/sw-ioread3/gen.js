'use strict';
// Writes hwtests/sw-ioread3/main.cpp: node hwtests/sw-ioread3/gen.js
const fs = require('fs'), path = require('path');
// All warm. What waits behind a JOY_STAT read that waits for the write queue: a RAM store (or none), the read (its value
// never read), k nops, then the NEXT access - a RAM load, a second JOY_STAT read, or a BIOS ROM load (each into its own
// register, never read either).
const NEXT = {
  M: ['lw $t4, 0x44($t6)', 'RAM lw'],
  J: ['lbu $t4, 0x1044($t9)', 'JOY_STAT lbu'],
  O: ['lw $t4, 0($t5)', 'ROM lw'],
  X: ['nop', 'nothing'],
};
const CASES = [];
for (const nk of ['M', 'J', 'O', 'X']) for (const sk of ['N', 'R']) for (const k of [0, 1, 2, 3, 4]) {
  if (nk === 'X' && k) continue;
  const words = [sk === 'N' ? 'nop' : 'sw $t1, 0x40($t6)', 'lbu $t0, 0x1044($t9)'];
  for (let j = 0; j < k; j++) words.push('nop');
  words.push(NEXT[nk][0]);
  CASES.push([`${sk}${nk}${k}`, `${sk === 'N' ? 'no store' : 'RAM sw'}, JOY_STAT lbu, ${k} nop${k === 1 ? '' : 's'}, ${NEXT[nk][1]}`, words]);
}
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw], i) => {
  const b = 's3B' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q('lui $t5, 0xbfc0') + q(`la $t6, ${b}_trial`) + q('lw $t1, 0x40($t6)');
  asm += q(`jal ${b}_entry`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_c`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  asm += q(`.org ${b}_trial + 0x200`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  asm += q('nop') + q('nop') + q('nop') + q('nop') + q('nop') + q('nop') + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t s3B${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `s3B${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '     ').slice(0, 5)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '      ').slice(0, 6)}${w}`).join('\n');

const src = `/*
 * cpu/sw-ioread3 - what waits behind an on-die read that waits for the write queue: the next access, k nops on (2026-10-12)
 *
 * WHY. hwtests/sw-ioread and sw-ioread2 (SCPH-1001 x3): behind a RAM store, a JOY_STAT read's access waits for the write
 * queue while the CPU runs on, and a reader of its value waits for it. v0.377.82 also holds the NEXT access until the
 * read is done, as if the CPU had waited (stIoEnd), from one console shape: hwtests/bios-window's lhu T2; lw ROM, 32 on
 * the consoles, 31 with the ROM load let go early. Here the next access 0-4 nops behind the read - a RAM load, a second
 * JOY_STAT read, a ROM load - with no store before (the control) and one RAM store right before the read; no loaded
 * value is ever read.
 *
 * WHAT IT DOES. All warm, sw-ioread's harness. 16 trials over the refresh:
${caseList}
 *
 * READ IT LIKE THIS. R against N at the same next access and k: what the store costs. With the CPU free and the next
 * access held as if the CPU had waited, R costs the queue's wait less the nops until the next access, and nothing with
 * nothing after (RX0, as sw-ioread's no-reader rows).
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js sw-ioread3\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t) {
    Span s = { 0xFFFF, 0 };
    t(0, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(0, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/sw-ioread3\\n");
    printf("The next access behind an on-die read behind a RAM store, warm code (Timer 2 cycles, fastest..slowest of 16).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span w = run(trials[i]);
        printf("  %-58s cold %3u..%-3u  warm %3u..%-3u  miss 0\\n", names[i], (unsigned)w.lo, (unsigned)w.hi, (unsigned)w.lo, (unsigned)w.hi);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp, ' + CASES.length + ' cases');
