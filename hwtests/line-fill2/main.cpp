typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { lf2B0_trial, lf2B1_trial, lf2B2_trial, lf2B3_trial, lf2B4_trial, lf2B5_trial, lf2B6_trial, lf2B7_trial };
static const unsigned lines[] = { 1, 2, 4, 8, 16, 32, 64, 128 };
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

