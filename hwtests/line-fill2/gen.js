'use strict';
// Writes hwtests/line-fill2/main.cpp: node hwtests/line-fill2/gen.js
const fs = require('fs'), path = require('path');
const NS = [1, 2, 4, 8, 16, 32, 64, 128];
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
NS.forEach((n, i) => {
  const b = 'lf2B' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  // a0 = evict?, a1 = spin turns; t9 = 1F800000h; the count in v0 - the whole trial here
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`jal ${b}_entry`) + q('nop');
  asm += q(`beqz $a0, ${b}_sp`) + q('nop') + q(`jal ${b}_ev`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_f`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  // the function F at +0x400: N lines, nops, jr ra at the last line's word 2 (its slot the last word)
  asm += q(`.org ${b}_trial + 0x400`) + q(`${b}_f:`);
  asm += q(`.rept ${n * 4 - 2}`) + q('nop') + q('.endr') + q('jr $ra') + q('nop');
  // the evictor 4 KB above F: the same N lines
  asm += q(`.org ${b}_trial + 0x1400`) + q(`${b}_ev:`);
  asm += q(`.rept ${n * 4 - 2}`) + q('nop') + q('.endr') + q('jr $ra') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = NS.map((_, i) => `extern "C" uint32_t lf2B${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = NS.map((_, i) => `lf2B${i}_trial`).join(', ');
const src = `/*
 * cpu/line-fill2 - line-fill with nothing else cold: N lines of nops filled back to back from a jal, left by jr ra, the
 * rest of the timed path warm (2026-10-12 small hours)
 *
 * WHY. hwtests/line-fill times a 4 KB function - the whole instruction cache - after FlushCache, and its "warm" pass is not
 * all hits: the function's lines and the harness's share indices, so the call and return paths miss too (this core's trace
 * at N = 32: three fills in the warm window). hwtests/miss-grid (SCPH-1001): every fill sequence costs a cycle more than
 * this core models; a model with that cycle reads line-fill's warm rows 2-3 over the consoles. This takes line-fill's
 * question without the conflicts: seq-miss2's in-slot harness, the function F at +400h (N lines, jr ra at the last line's
 * word 2), an evictor of the same N lines 4 KB above; cold (evicted) against warm, 16 trials over the refresh.
 *
 * READ IT LIKE THIS. cold - warm against N: the slope is the line interval (9 + refresh), the intercept the sequence's own
 * cost - miss-grid's extra cycle once, or once a line, or not at all.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js line-fill2\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const unsigned lines[] = { ${NS.join(', ')} };
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/line-fill2\\n");
    printf("N lines filled back to back, nothing else cold (Timer 2 cycles, fastest..slowest of 16; cold / warm).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span c = run(trials[i], 1), w = run(trials[i], 0);
        printf("  N=%-4u cold %5u..%-5u  warm %5u..%-5u  cold-warm %d\\n", lines[i], (unsigned)c.lo, (unsigned)c.hi, (unsigned)w.lo, (unsigned)w.hi, (int)c.lo - (int)w.lo);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
