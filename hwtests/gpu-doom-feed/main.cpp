/*
 * gpu-doom-feed: A GAME'S OWN PRIMITIVE FEED, CALL FOR CALL - how often is GPUSTAT bit 26 up when the game asks?
 *
 * WHY. The doom-probe session's patched Doom (USA) on the second SCPH-5501 (STATUS "The Doom probe", "Inside the drawer" and
 * "Version 3"): in play the console's drawing loop runs ~3% longer than this core's, and the count of words left for the
 * frame's DrawOTag says why - the console hand-feeds ~192 more words a pass. The game's feed (W_AddPrim, PSXDOOM-RE psxmain.c)
 * copies each primitive into a ring in RAM and then sends queued packets to GP0 for as long as GPUSTAT bit 26 reads 1,
 * breaking at the first 0: it never waits, so a GPU that is ready sooner is fed MORE words by hand. The feed is almost all
 * GP0(24h), textured triangles a pixel or two wide and 10-30 rows tall (wall columns), one every ~360 cycles.
 *
 * WHAT. Two play passes' streams as the emulator ran them (stream.h, generated by gen.js from the doom-probe session's
 * experiments/doomtas/probe/logs/primdump-pass428.json and -pass496.json: each call's cycle from the first and its packet).
 * The same ring and the same loop, each call begun at its own cycle from the first (or at once if the one before ran past
 * it), from the game's own place in the frame after VBlank; under the game's display mode (256x240), drawing area, offset,
 * texture window and page. The textures are this test's own (VRAM filled with one colour): only the words are the game's.
 * Nothing prints inside. Per call: how late it began, how long it took, the words it sent. Per run: the words fed by hand,
 * the words left, the time to feed what was left (a stand-in for the DrawOTag + DrawSync), the whole.
 * Six runs a pass; the first is printed call by call, the others as totals and the count of calls that sent differently.
 *
 * READ IT. "left" larger in the emulator than on the console is the finding again, on a test both can run: then the rows
 * say which calls the console sent at that this core did not. No assertions.
 *
 * THE RULE: run it here first: `node tools/hwrunner.js gpu-doom-feed --emu`.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>
#include "stream.h"

#define T2_COUNT 0x1F801120u
#define T2_MODE  0x1F801124u
#define I_STAT   0x1F801070u
#define GP0 0x1F801810u
#define GP1 0x1F801814u

static uint32_t clk; static uint16_t lastT;
static uint32_t now() { const uint16_t t = read16(T2_COUNT); clk += (uint16_t)(t - lastT); lastT = t; return clk; }
static void waitReady() { const uint32_t t0 = now(); while ((read32(GP1) & 0x14000000u) != 0x14000000u && now() - t0 < 4000000u) {} }
static uint32_t xy(int x, int y) { return ((uint32_t)(y & 0xFFFF) << 16) | (uint32_t)(x & 0xFFFF); }

/* the ring: [length][words ...] packets back to back; head = the next to send, tail = the next free */
static uint32_t ring[16384];
static uint32_t* volatile headP;
static uint32_t* volatile tailP;

/* W_AddPrim's shape: copy the packet in, then send packets while bit 26 reads 1; break at the first 0 */
static void __attribute__((noinline)) feedPrim(const uint32_t* prim) {
    uint32_t* e = tailP;
    int length = (int)prim[0];
    *e = (uint32_t)length;
    const uint32_t* s = prim + 1;
    while (length--) { e++; *e = *s++; }
    tailP = e + 1;
    while (headP != tailP) {
        if ((*(volatile uint32_t*)GP1 & 0x04000000u) == 0) break;
        uint32_t* p = headP;
        length = (int)*p;
        headP = p + length + 1;
        while (length--) { p++; *(volatile uint32_t*)GP0 = *p; }
    }
}

static const int MAXC = 1300;
static uint32_t tIn[MAXC], tOut[MAXC];
static uint16_t hd[MAXC];
struct Tot { uint32_t fed, left, drain, whole; int differ; };
static Tot tot[2][6];
static uint16_t late0[2][MAXC], dur0[2][MAXC];
static uint8_t sent0[2][MAXC];

static void runPass(int p, int r, const uint32_t* W, const uint32_t* T, int calls, const uint32_t* env, uint32_t lead) {
    waitReady();
    for (int i = 0; i < 5; i++) write32(GP0, env[i]);
    write32(GP0, 0xE6000000u);
    waitReady();
    headP = ring; tailP = ring;
    write32(I_STAT, ~1u);
    { const uint32_t t0 = now(); while (!(read32(I_STAT) & 1u) && now() - t0 < 2000000u) {} }
    const uint32_t start = now() + lead;
    const uint32_t* w = W;
    for (int i = 0; i < calls; i++) {
        const uint32_t at = start + T[i];
        while ((int32_t)(now() - at) < 0) {}
        tIn[i] = now();
        feedPrim(w);
        tOut[i] = now();
        hd[i] = (uint16_t)(headP - ring);
        w += w[0] + 1;
    }
    const uint32_t tEnd = now();
    Tot& o = tot[p][r];
    o.fed = (uint32_t)(headP - ring); o.left = (uint32_t)(tailP - headP);
    /* what is left, a packet at each bit 26 (the game hands it to DrawOTag; this is only to time the GPU's backlog) */
    while (headP != tailP && now() - tEnd < 4000000u) {
        if ((read32(GP1) & 0x04000000u) == 0) continue;
        uint32_t* q = headP; int length = (int)*q; headP = q + length + 1;
        while (length--) { q++; write32(GP0, *q); }
    }
    waitReady();
    o.drain = now() - tEnd; o.whole = tEnd - start; o.differ = 0;
    uint16_t prev = 0;
    for (int i = 0; i < calls; i++) {
        const uint32_t sc = start + T[i], la = tIn[i] - sc, du = tOut[i] - tIn[i];
        const uint8_t se = (uint8_t)(hd[i] - prev); prev = hd[i];
        if (r == 0) { late0[p][i] = (uint16_t)(la > 65535u ? 65535u : la); dur0[p][i] = (uint16_t)(du > 65535u ? 65535u : du); sent0[p][i] = se; }
        else if (se != sent0[p][i]) o.differ++;
    }
}

int main() {
    printf("\ngpu/gpu-doom-feed\n");
    printf("Two Doom play passes' primitive streams fed by the game's loop (send while GPUSTAT bit 26 reads 1), each call at\n");
    printf("its own cycle. Per call: late, cycles, words sent. No assertions.\n\n");
    const uint32_t stat0 = read32(GP1);
    EnterCriticalSection();
    const uint16_t m2 = read16(T2_MODE);
    write16(T2_MODE, 0);
    lastT = read16(T2_COUNT); clk = 0;
    write32(GP1, 0x04000000u);
    write32(GP0, 0xE1000400u);
    write32(GP0, 0xE2000000u);
    write32(GP0, 0xE3000000u);
    write32(GP0, 0xE4000000u | (511u << 10) | 1023u);
    write32(GP0, 0xE5000000u);
    write32(GP0, 0xE6000000u);
    /* VRAM one colour (not 0000h: a texel of 0 is not drawn), the two frames black */
    for (int q = 0; q < 4; q++) { waitReady(); write32(GP0, 0x02305070u); write32(GP0, xy((q & 1) * 512, (q >> 1) * 256)); write32(GP0, xy(512, 256)); }
    waitReady();
    write32(GP0, 0x02000000u); write32(GP0, xy(0, 0)); write32(GP0, xy(512, 240));
    waitReady();
    write32(GP1, 0x08000000u); write32(GP1, 0x03000000u);          /* 256x240, NTSC, 15-bit */
    write32(GP1, 0x05000000u);
    write32(GP1, 0x06000000u | ((0x260u + 2560u) << 12) | 0x260u);
    write32(GP1, 0x07000000u | ((16u + 240u) << 10) | 16u);
    /* the code warm, then six runs a pass */
    runPass(0, 0, P0_W, P0_T, 40, P0_ENV, 2000u);
    for (int r = 0; r < 6; r++) runPass(0, r, P0_W, P0_T, P0_CALLS, P0_ENV, P0_LEAD);
    for (int r = 0; r < 6; r++) runPass(1, r, P1_W, P1_T, P1_CALLS, P1_ENV, P1_LEAD);
    waitReady();
    write32(GP0, 0xE3000000u); write32(GP0, 0xE4000000u | (511u << 10) | 1023u); write32(GP0, 0xE5000000u); write32(GP0, 0xE2000000u);
    write32(GP1, 0x08000000u | ((stat0 >> 17) & 0x3F) | (((stat0 >> 16) & 1) << 6) | (((stat0 >> 14) & 1) << 7));
    write32(GP1, 0x03000000u | ((stat0 >> 23) & 1));
    waitReady();
    write16(T2_MODE, m2);
    ExitCriticalSection();
    static const int PASS[2] = { P0_PASS, P1_PASS }, CALLS[2] = { P0_CALLS, P1_CALLS }, WORDS[2] = { P0_WORDS, P1_WORDS };
    for (int p = 0; p < 2; p++) {
        printf("pass %d: %d calls, %d words (lengths included)\n", PASS[p], CALLS[p], WORDS[p]);
        for (int r = 0; r < 6; r++)
            printf("  run %d: fed %u  left %u  feeding the rest %u  the calls %u  calls sending unlike run 0: %d\n", r,
                   (unsigned)tot[p][r].fed, (unsigned)tot[p][r].left, (unsigned)tot[p][r].drain, (unsigned)tot[p][r].whole, tot[p][r].differ);
    }
    for (int p = 0; p < 2; p++) {
        printf("pass %d run 0, per call: late cycles sent\n", PASS[p]);
        for (int i = 0; i < CALLS[p]; i++) {
            printf(" %u %u %u", (unsigned)late0[p][i], (unsigned)dur0[p][i], (unsigned)sent0[p][i]);
            if (i % 16 == 15 || i == CALLS[p] - 1) printf("\n");
        }
    }
    printf("\ndone\n");
    return 0;
}
