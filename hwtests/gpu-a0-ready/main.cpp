static uint32_t up0(uint32_t xy, uint32_t wh, uint32_t data) {
    uint32_t st;
    __asm__ volatile(
        ".set noreorder\n"
        "lui $t0, 0x1f80\n"
        "lui $t1, 0xa000\n"
        "sw $t1, 0x1810($t0)\n"
        "sw %1, 0x1810($t0)\n"
        "sw %2, 0x1810($t0)\n"
        "sw %3, 0x1810($t0)\n"
        "lw %0, 0x1814($t0)\n"
        "nop\n"
        ".set reorder\n"
        : "=r"(st) : "r"(xy), "r"(wh), "r"(data) : "t0", "t1", "memory");
    return st;
}
