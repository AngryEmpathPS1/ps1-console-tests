/*
 * cpu/hold-read - a read behind a store held in a streaming line: does it wait for the store, by the store's device?
 * (2026-10-12)
 *
 * WHY. hwtests/st-land (SCPH-1001 x3): a Timer 2 counter reset written from a cold line lands after the stream's closing
 * stall, and cold-bracket's and access-time's own resets land there although an on-die read of another device follows them
 * in the same sequence - the read goes around the held store. ps1-tests' timer-dump (its console's RTS wired to Timer 0's
 * clock) says a Timer 0 read does NOT go around a held SIO1 store (it sees the RTS edge). This core lets reads go around
 * held TIMER stores only - measured, not understood. This asks it directly: a store at a cold line's word 0 - to Timer 0's
 * or Timer 1's target, to I_MASK or DPCR (each its own value back) - and a Timer 2 read at word 1 or 3, whose count says when
 * it sampled.
 *
 * WHAT IT DOES. fix-shadow's harness; the count starts at a warm counter reset, C (entered at word 0 by a jal) holds the
 * store and the Timer 2 read, the result is that read's count. 16 trials over the refresh, cold against warm:
 *   N-1  no store (a nop) at word 0, Timer 2 read at word 1
 *   N-3  no store (a nop) at word 0, Timer 2 read at word 3
 *   T0-1 Timer 0 target at word 0, Timer 2 read at word 1
 *   T0-3 Timer 0 target at word 0, Timer 2 read at word 3
 *   T1-1 Timer 1 target at word 0, Timer 2 read at word 1
 *   T1-3 Timer 1 target at word 0, Timer 2 read at word 3
 *   IM-1 I_MASK, its own value at word 0, Timer 2 read at word 1
 *   IM-3 I_MASK, its own value at word 0, Timer 2 read at word 3
 *   DP-1 DPCR, its own value at word 0, Timer 2 read at word 1
 *   DP-3 DPCR, its own value at word 0, Timer 2 read at word 3
 *
 * READ IT LIKE THIS. Each store's row against the N row at the same word: equal - the read went around the store, or the
 * store cost the read nothing; more - the read waited for it.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: `node hwtests/run.js hold-read`. Generated by gen.js.
 */
