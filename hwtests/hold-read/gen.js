'use strict';
// Writes hwtests/hold-read/main.cpp: node hwtests/hold-read/gen.js
const fs = require('fs'), path = require('path');
// t9 = 1F800000h; t1 = the value the store writes (its register's own value, read before the timed pass, or the target)
// C (entered at word 0 by a jal): the store at word 0, the Timer 2 read at word 1 (its count is the result), nops; D warm.
const STORES = [
  ['N', 'no store (a nop)', 'nop', null],
  ['T0', 'Timer 0 target', 'sh $t1, 0x1108($t9)', 0x1108],
  ['T1', 'Timer 1 target', 'sh $t1, 0x1118($t9)', 0x1118],
  ['IM', 'I_MASK, its own value', 'sh $t1, 0x1074($t9)', 0x1074],
  ['DP', 'DPCR, its own value', 'sw $t1, 0x10f0($t9)', 0x10f0],
];
const CASES = [];
for (const [k, w, st, reg] of STORES) {
  CASES.push([`${k}-1`, `${w} at word 0, Timer 2 read at word 1`, [st, 'lhu $t3, 0x1120($t9)', 'nop', 'nop'], reg]);
  CASES.push([`${k}-3`, `${w} at word 0, Timer 2 read at word 3`, [st, 'nop', 'nop', 'lhu $t3, 0x1120($t9)'], reg]);
}
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw, reg], i) => {
  const b = 'hrB' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  // a0 = evict?, a1 = spin turns; t9 = 1F800000h; t1 = the stored value (its register's own); the count in v0
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80');
  if (reg === 0x10f0) asm += q('lw $t1, 0x10f0($t9)');
  else if (reg === 0x1074) asm += q('lhu $t1, 0x1074($t9)');
  else asm += q('li $t1, 0xffff');
  asm += q(`jal ${b}_entry`) + q('nop');
  asm += q(`beqz $a0, ${b}_sp`) + q('nop') + q(`jal ${b}_ev`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_c`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  // C at +0x200: the store, the Timer 2 read, nops; D at +0x210 warm (nops, jr ra)
  asm += q(`.org ${b}_trial + 0x200`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  asm += q('nop') + q('nop') + q('nop') + q('nop') + q('jr $ra') + q('nop') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x1200`) + q(`${b}_ev:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t hrB${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `hrB${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '    ').slice(0, 4)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '     ').slice(0, 5)}${w}`).join('\n');

const src = `/*
 * cpu/hold-read - a read behind a store held in a streaming line: does it wait for the store, by the store's device?
 * (2026-10-12)
 *
 * WHY. hwtests/st-land (SCPH-1001 x3): a Timer 2 counter reset written from a cold line lands after the stream's closing
 * stall, and cold-bracket's and access-time's own resets land there although an on-die read of another device follows them
 * in the same sequence - the read goes around the held store. ps1-tests' timer-dump (its console's RTS wired to Timer 0's
 * clock) says a Timer 0 read does NOT go around a held SIO1 store (it sees the RTS edge). This core lets reads go around
 * held TIMER stores only - measured, not understood. This asks it directly: a store at a cold line's word 0 - to Timer 0's
 * or Timer 1's target, to I_MASK or DPCR (each its own value back) - and a Timer 2 read at word 1 or 3, whose count says when
 * it sampled.
 *
 * WHAT IT DOES. fix-shadow's harness; the count starts at a warm counter reset, C (entered at word 0 by a jal) holds the
 * store and the Timer 2 read, the result is that read's count. 16 trials over the refresh, cold against warm:
${caseList}
 *
 * READ IT LIKE THIS. Each store's row against the N row at the same word: equal - the read went around the store, or the
 * store cost the read nothing; more - the read waited for it.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js hold-read\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/hold-read\\n");
    printf("A Timer 2 read behind a store held in a streaming line (Timer 2 cycles, fastest..slowest of 16; cold / warm).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    const uint16_t t0t = read16(0x1F801108u), t1t = read16(0x1F801118u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span c = run(trials[i], 1), w = run(trials[i], 0);
        printf("  %-56s cold %3u..%-3u  warm %3u..%-3u  miss %d\\n", names[i], (unsigned)c.lo, (unsigned)c.hi, (unsigned)w.lo, (unsigned)w.hi, (int)c.lo - (int)w.lo);
    }
    write16(0x1F801108u, t0t);
    write16(0x1F801118u, t1t);
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
