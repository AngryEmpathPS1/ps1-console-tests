'use strict';
// Writes hwtests/sw-sample/main.cpp: node hwtests/sw-sample/gen.js
const fs = require('fs'), path = require('path');
// All warm. WHEN a Timer 2 read behind queued RAM stores takes its sample, by the stores' layout and distance: lhu T2
// (t0), then the stores, g nops, lhu T2 (t1); the trial returns t1 - t0. Layouts:
//   N  none - four nops after t0;
//   R  one RAM sw, four nops after t0 (out of t0's shadow);
//   P  sw; nop; sw (one 1 KB block - bios-window's sw; jal; sw), four nops after t0;
//   D  a RAM sw in t0's delay slot, then the g nops: counter-bracket's own shape.
const PRE = {
  N: ['nop', 'nop', 'nop', 'nop', 'nop', 'nop', 'nop'],
  R: ['nop', 'nop', 'nop', 'nop', 'nop', 'nop', 'sw $t1, 0x40($t6)'],
  P: ['nop', 'nop', 'nop', 'nop', 'sw $t1, 0x40($t6)', 'nop', 'sw $t1, 0x44($t6)'],
  D: ['sw $t1, 0x40($t6)'],
};
const WHAT = { N: 'no store', R: 'RAM sw', P: 'sw;nop;sw', D: 'sw in t0 delay slot' };
const CASES = [];
for (const sk of ['N', 'R', 'P', 'D']) for (const g of [0, 1, 2, 3, 4]) {
  const words = ['lhu $t0, 0x1120($t9)', ...PRE[sk]];
  for (let j = 0; j < g; j++) words.push('nop');
  words.push('lhu $t3, 0x1120($t9)');
  CASES.push([`${sk}${g}`, `${WHAT[sk]}, ${g} nop${g === 1 ? '' : 's'}, then the second read`, words]);
}
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw], i) => {
  const b = 'smB' + i;
  // Called twice per sample (the first warms the line): spin $a1 in between to walk the refresh.
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`la $t6, ${b}_trial`) + q('lw $t1, 0x40($t6)');
  asm += q(`jal ${b}_c`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_c`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  asm += q('nop') + q('subu $v0, $t3, $t0') + q('jr $ra') + q('andi $v0, $v0, 0xffff');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t smB${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `smB${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '    ').slice(0, 4)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '     ').slice(0, 5)}${w}`).join('\n');

const src = `/*
 * cpu/sw-sample - WHEN a Timer 2 read behind queued RAM stores takes its sample, by the stores' layout (2026-10-12)
 *
 * WHY. hwtests/sw-ioread..sw-ioread4 (SCPH-1001, 9001, 7501, 5501 alike) time a queued on-die read's VALUE (its reader)
 * and the NEXT ACCESS behind it - both late by the queue's wait less a cycle - but not the read's own sample. Two
 * programs disagree about it at the smallest wait: counter-bracket (a store in the first read's delay slot, then N
 * nops) needs the second read to sample after the whole wait at N = 0..2; bios-window (sw; jal; sw, then the read three
 * instructions on) needs it not to sample late at all. Here the sample itself, by layout: two lhu of Timer 2, the stores
 * between, g nops before the second; the bracket t1 - t0.
 *
 * WHAT IT DOES. All warm; each trial called twice (the second timed), 16 times over the refresh:
${caseList}
 *
 * READ IT LIKE THIS. R, P or D against N at the same g: how much later the second read samples for the stores.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js sw-sample\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t) {
    Span s = { 0xFFFF, 0 };
    t(0, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(0, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/sw-sample\\n");
    printf("A Timer 2 read behind queued RAM stores: the bracket between two reads, warm code (fastest..slowest of 16).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span w = run(trials[i]);
        printf("  %-48s cold %3u..%-3u  warm %3u..%-3u  miss 0\\n", names[i], (unsigned)w.lo, (unsigned)w.hi, (unsigned)w.lo, (unsigned)w.hi);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp, ' + CASES.length + ' cases');
