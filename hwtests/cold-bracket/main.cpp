#define T2_MODE  0x1F801124u
typedef uint32_t (*Block)(void);
extern "C" void __attribute__((noinline, aligned(64))) cbStub(void) { __asm__ volatile(""); }
static void __attribute__((noinline, aligned(64))) evict(void) {
    __asm__ volatile(".set push\n.set noreorder\n.rept 1152\nnop\n.endr\n.set pop\n");
}
static uint32_t __attribute__((noinline, aligned(64))) b0(void) { /* stub nop100 w0 */
    uint32_t r;
    __asm__ volatile(".set push\n.set noreorder\n.set noat\n"
        "lui $s0, 0x1f80\n"
        ".balign 64\n"
        "nop\n"
        "nop\n"
        "jal cbStub\n"
        "nop\n"
        "lhu $v1, 0x1124($s0)\n"
        "sh $zero, 0x1124($s0)\n"
        "lhu $v0, 0x1124($s0)\n"
        "andi $v1, $v1, 0xffff\n"
        "sh $zero, 0x1120($s0)\n"
        "addiu $v0, $zero, 100\n"
        "1:\n"
        "nop\n"
        "addiu $v0, $v0, -1\n"
        "bnez $v0, 1b\n"
        "nop\n"
        "lui $v0, 0x1f80\n"
        "lhu %0, 0x1120($v0)\n"
        "lhu $v0, 0x1124($v0)\n"
        "nop\n"
        ".set pop\n" : "=&r"(r) : : "v0", "v1", "a0", "a1", "a2", "a3", "t0", "t1", "t2", "t3", "t4", "t5", "t6", "t7", "t8", "t9", "s0", "ra", "memory");
    return r & 0xFFFF; }
