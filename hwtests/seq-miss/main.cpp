typedef void (*Fn)(void);
static const Fn entries[] = { smB0_entry, smB1_entry, smB2_entry, smB3_entry, smB4_entry, smB5_entry };
static const Fn evictors[] = { smB0_ev, smB1_ev, smB2_ev, smB3_ev, smB4_ev, smB5_ev };
static const char* const names[] = {
    "J0  jal to word 0 of C",
    "J1  jal to word 1 of C",
    "J2  jal to word 2 of C",
    "J3  jal to word 3 of C",
    "S   fall from warm W (entered at word 0) into C",
    "S3  fall from warm W (entered at word 3) into C"
};
struct Span { uint32_t lo, hi; };
static Span trials(Fn entry, Fn ev) {
    Span s = { 0xFFFF, 0 };
    for (uint32_t k = 0; k < 17; k++) {
        callBlock(entry);                      /* everything warm */
        if (ev) ev();
        spin(k * 8);
        const uint32_t v = callBlock(entry);
        if (k == 0) continue;                  /* the first pass warms the evictor */
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

