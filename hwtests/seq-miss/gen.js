'use strict';
// Writes hwtests/seq-miss/main.cpp: node hwtests/seq-miss/gen.js
const fs = require('fs'), path = require('path');
// [name, label, how the cold line C is entered]
const CASES = [
  ['J0', 'jal to word 0 of C', 'c0'],
  ['J1', 'jal to word 1 of C', 'c1'],
  ['J2', 'jal to word 2 of C', 'c2'],
  ['J3', 'jal to word 3 of C', 'c3'],
  ['S', 'fall from warm W (entered at word 0) into C', 'w0'],
  ['S3', 'fall from warm W (entered at word 3) into C', 'w3'],
];
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([n, , tgt], i) => {
  const b = 'smB' + i;
  asm += q('.balign 8192') + q(`.global ${b}`) + q(`${b}:`);
  // w16 / r16, warm stubs (at-split's write16 / read16)
  asm += q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  // the entry at +0x100
  asm += q('.balign 256') + q(`${b}_entry:`);
  asm += q('nop') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_${tgt}`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  // W at +0x1F0, C at +0x200, D at +0x210
  asm += q(`.org ${b} + 0x1F0`);
  asm += q(`${b}_w0:`) + q('nop') + q('nop') + q('nop') + q(`${b}_w3:`) + q('nop');
  asm += q(`${b}_c0:`) + q('nop') + q(`${b}_c1:`) + q('nop') + q(`${b}_c2:`) + q('nop') + q(`${b}_c3:`) + q('nop');
  asm += q(`${b}_d:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
  // the evictor page: jr ra at C's index
  asm += q(`.org ${b} + 0x1200`) + q(`${b}_ev:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" void smB${i}_entry(void); extern "C" void smB${i}_ev(void);`).join('\n');
const tabE = CASES.map((_, i) => `smB${i}_entry`).join(', ');
const tabV = CASES.map((_, i) => `smB${i}_ev`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '   ').slice(0, 3)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '    ').slice(0, 4)}${w}`).join('\n');

const src = `/*
 * cpu/seq-miss - a cold line entered by a jump against the same line entered by falling through from a cached line, with
 * the bus idle (2026-10-11 night)
 *
 * WHY. hwtests/cold-window on the SCPH-1001 (three runs, identical): each of at-split's two cold lines costs a cycle more
 * on the console than this core (L1 cold 410 / here 409, L2 cold 412 / 411; both cold 417 / 415 - at-split's +2), and
 * both are entered by FALLING THROUGH from a line already in the cache, the bus idle. The cold-code model (v0.377.75's
 * stream) was fitted on lines entered by a jump (load-fill, cold-branch, shadow-miss) and reads those right. Is the
 * sequential entry a cycle slower, or any lone miss?
 *
 * WHAT IT DOES. Interrupts off, Timer 2 at the system clock. Each case has its own 8 KB slot: warm stubs reset and read
 * the counter (cold-window's), and between them the entry jal's into the code around the cold line C (at +0x200): W, the
 * line before it (+0x1F0), and D after it (+0x210, jr ra). C is made cold by a jr ra 4 KB above it (the evictor); the
 * same run with C warm is the control. 16 trials a case, spread over the refresh, fastest..slowest:
${caseList}
 *
 * READ IT LIKE THIS. cold - warm is the miss's cost. J0 against S: the same line, the same word, entered by a jump or by
 * falling through. S3: W holds one word (entered at its last), the rest of it never fetched.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js seq-miss\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

extern "C" uint32_t callBlock(void (*entry)(void));
extern "C" void spin(uint32_t n);
__asm__(".text\\n.set push\\n.set noreorder\\n.set noat\\n.balign 16\\n"
        ".global callBlock\\ncallBlock:\\nmove $t8, $ra\\nlui $t9, 0x1f80\\njr $a0\\nnop\\n"
        ".global spin\\nspin:\\n1:\\nbnez $a0, 1b\\naddiu $a0, $a0, -1\\njr $ra\\nnop\\n"
        ".set pop\\n");

typedef void (*Fn)(void);
static const Fn entries[] = { ${tabE} };
static const Fn evictors[] = { ${tabV} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span trials(Fn entry, Fn ev) {
    Span s = { 0xFFFF, 0 };
    for (uint32_t k = 0; k < 17; k++) {
        callBlock(entry);                      /* everything warm */
        if (ev) ev();
        spin(k * 8);
        const uint32_t v = callBlock(entry);
        if (k == 0) continue;                  /* the first pass warms the evictor */
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/seq-miss\\n");
    printf("A cold line entered by a jump or by falling through (Timer 2 cycles, fastest..slowest of 16; cold / warm).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(entries) / sizeof(entries[0]); i++) {
        const Span c = trials(entries[i], evictors[i]), w = trials(entries[i], 0);
        printf("  %-50s cold %3u..%-3u  warm %3u..%-3u  miss %d\\n", names[i], (unsigned)c.lo, (unsigned)c.hi, (unsigned)w.lo, (unsigned)w.hi, (int)c.lo - (int)w.lo);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
