/*
 * cpu/unc-load-phase - uncached RAM loads at every phase from a DRAM refresh: alone, in runs, with a reader one to three on,
 * a reader behind a second load, a scratchpad or I/O load right behind (2026-10-29 night)
 *
 * WHY. v0.377.216 holds an uncached load's read for the fetch three on (UNC_MEM_FETCH) only when its next two neither load nor
 * touch its register; hwtests/unc-store-phase's LLS says the console puts each of two back-to-back loads' reads before its
 * own fetch three on, and the shapes v0.377.216 does not hold are fitted on unc-load's averages only. This times each at every
 * phase, where each cost is a whole number.
 *
 * WHAT IT DOES. unc-store-phase's harness (refresh-warm's rcSweep / rcCalib; experiments/_mkuncload.js): each block called
 * through its KSEG1 alias, 24 instructions and `jr ra; nop`; loads read RAM+0..12 (t5..t8), the scratchpad 1F800000h and
 * Timer 2 (through t4, which rcSweep sets before every trial), the store writes RAM+128.
 *   U     24 nops
 *   L     lw; 23 nops
 *   LL    lw; lw (another register); 22 nops
 *   LLL   three loads back to back; 21 nops
 *   LLLL  four loads back to back; 20 nops
 *   L_L   lw; nop; lw; 21 nops
 *   LU1   lw t5; addu t9, t5, t5 (its reader one on); 22 nops
 *   LU2   lw t5; nop; addu (its reader two on); 21 nops
 *   LU3   lw t5; nop; nop; addu (its reader three on); 20 nops
 *   LLU2  lw t5; lw t6; addu t9, t5, t5 (the first one's reader behind a second load); 21 nops
 *   LSP   lw t5, RAM; lw t6, scratchpad; 22 nops
 *   LIO   lw t5, RAM; lhu t6, Timer 2; 22 nops
 *   LLS   lw; lw; sw (unc-store-phase's, for alignment); 21 nops
 * Each prints its commonest cost, then the cost by x = (F - the first Timer 2 read's phase) mod 256, sixteen to a line.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: `node hwtests/run.js unc-load-phase --frames=3000 --quiet=600`.
 */
