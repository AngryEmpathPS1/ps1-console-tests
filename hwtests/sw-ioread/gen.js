'use strict';
// Writes hwtests/sw-ioread/main.cpp: node hwtests/sw-ioread/gen.js
const fs = require('fs'), path = require('path');
// All warm. t9 = 1F800000h, t6 = this slot (a RAM word to store), t1 = the stored value. The count runs from a warm
// counter reset to the closing read; the block in C: a store, a JOY_STAT lbu into t0, k nops, and a reader of t0 (or not).
const STORES = [['N', 'no store', 'nop'], ['R', 'RAM sw', 'sw $t1, 0x40($t6)'], ['T', 'Timer 0 target sh', 'sh $t1, 0x1108($t9)']];
const CASES = [];
for (const [sk, sw, st] of STORES) for (const rd of [false, true]) for (let k = 0; k <= 3; k++) {
  const words = [st, 'lbu $t0, 0x1044($t9)'];
  for (let j = 0; j < k; j++) words.push('nop');
  words.push(rd ? 'addu $t2, $t0, $zero' : 'nop');
  CASES.push([`${sk}${rd ? 'R' : '-'}${k}`, `${sw}, JOY_STAT lbu, ${k} nop${k === 1 ? '' : 's'}, ${rd ? 'its reader' : 'no reader'}`, words]);
}
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw], i) => {
  const b = 'swB' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  // a0 = evict? (unused: all warm), a1 = spin turns; the count in v0
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`la $t6, ${b}_trial`) + q('lw $t1, 0x40($t6)');
  asm += q(`jal ${b}_entry`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_c`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  asm += q(`.org ${b}_trial + 0x200`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  asm += q('nop') + q('nop') + q('nop') + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t swB${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `swB${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '    ').slice(0, 4)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '     ').slice(0, 5)}${w}`).join('\n');

const src = `/*
 * cpu/sw-ioread - an on-die read right behind a store, in warm code: does the CPU wait for the write queue, or only the
 * read's own access - and does a reader of its value pay it? (2026-10-12)
 *
 * WHY. hwtests/store-stall (SCPH-1001 x3): a RAM store then a JOY_STAT load in warm code costs nothing over the load alone
 * (18 and 18); this core charges 3, an on-die read waiting for the write queue all but IO_WB_OVERLAP - fitted on
 * hwtests/counter-bracket, where the read's own SAMPLE is what is timed (two Timer 2 reads around a RAM store: 8 apart).
 * Both fit if the read's access waits for the queue but the CPU runs on until something reads the value. This asks it:
 * a store (none, RAM, an on-die register), a JOY_STAT read, 0-3 nops, and a reader of the value or not.
 *
 * WHAT IT DOES. All warm (each case's own 8 KB slot, run once before it is timed): the count from a warm counter reset to
 * the closing read, 16 trials over the refresh:
${caseList}
 *
 * READ IT LIKE THIS. Against the N rows (no store): the store's cost to the CPU with no reader, and where a reader starts
 * paying the read's wait for the store.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js sw-ioread\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t) {
    Span s = { 0xFFFF, 0 };
    t(0, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(0, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/sw-ioread\\n");
    printf("An on-die read behind a store, warm code (Timer 2 cycles, fastest..slowest of 16).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    const uint16_t t0t = read16(0x1F801108u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span w = run(trials[i]);
        printf("  %-52s cold %3u..%-3u  warm %3u..%-3u  miss 0\\n", names[i], (unsigned)w.lo, (unsigned)w.hi, (unsigned)w.lo, (unsigned)w.hi);
    }
    write16(0x1F801108u, t0t);
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
