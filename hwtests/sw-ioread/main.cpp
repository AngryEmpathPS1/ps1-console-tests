static Span run(Trial t) {
    Span s = { 0xFFFF, 0 };
    t(0, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(0, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

