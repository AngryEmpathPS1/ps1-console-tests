'use strict';
// Writes hwtests/miss-grid/main.cpp: node hwtests/miss-grid/gen.js
const fs = require('fs'), path = require('path');
const ENTRIES = [
  ['J', 'jal to C', 'c', 0],
  ['F', 'fall from warm W into C', 'w', 0],
  ['P', 'W and C cold, jal to W', 'w', 1],
];
const EXITS = [
  ['S', 'run C, fall into warm D', ['nop', 'nop', 'nop', 'nop']],
  ['B0', 'taken branch at C word 0', ['BR', 'nop', 'nop', 'nop']],
  ['B1', 'taken branch at C word 1', ['nop', 'BR', 'nop', 'nop']],
  ['B2', 'taken branch at C word 2', ['nop', 'nop', 'BR', 'nop']],
  ['B3', 'taken branch at C word 3 (its slot D word 0)', ['nop', 'nop', 'nop', 'BR']],
];
const CASES = [];
for (const [en, el, tgt, evw] of ENTRIES) for (const [ex, xl, words] of EXITS) CASES.push([en + '-' + ex, el + ', ' + xl, tgt, evw, words]);
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , tgt, evw, words], i) => {
  const b = 'mgB' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  // a0 = evict?, a1 = spin turns; t9 = 1F800000h; the count in v0 - the whole trial here, nothing else cold in the timed pass
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`jal ${b}_entry`) + q('nop');
  asm += q(`beqz $a0, ${b}_sp`) + q('nop') + q(`jal ${b}_ev`) + q('nop');
  if (evw) asm += q(`jal ${b}_evw`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_${tgt}`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  // W at +0x1F0, C at +0x200 (its four words by the exit), D at +0x210 (nop; jr ra; nop), X at +0x300 (jr ra; nop)
  asm += q(`.org ${b}_trial + 0x1F0`) + q(`${b}_w:`) + q('nop') + q('nop') + q('nop') + q('nop');
  asm += q(`${b}_c:`);
  for (const w of words) asm += q(w === 'BR' ? `beq $zero, $zero, ${b}_x` : w);
  asm += q(`${b}_d:`) + q('nop') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x300`) + q(`${b}_x:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
  // the evictors 4 KB above: W's index and C's
  asm += q(`.org ${b}_trial + 0x11F0`) + q(`${b}_evw:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
  asm += q(`${b}_ev:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t mgB${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `mgB${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '     ').slice(0, 5)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '      ').slice(0, 6)}${w}`).join('\n');

const src = `/*
 * cpu/miss-grid - one cold line C by how it is entered and how it is left: the extra cycle a lone miss pays on the
 * consoles, taken apart (2026-10-12 small hours)
 *
 * WHY. hwtests/seq-miss2 on the SCPH-1001 (three runs, identical; nothing else cold): every lone miss costs 5 at every
 * entry word, by a jump or a fall-through, C left by falling into the next line. hwtests/cold-branch (9001): a line
 * entered by a jump and left by a taken branch whose slot is its last word costs 4. A fixed 4-cycle word reads cold-branch
 * and the fitted corpus; the fifth cycle depends on how the line is entered and left, and a rule fitted to the three
 * programs that show it moves line-fill's and refresh-cold's rows. This is the grid: entered by a jal (J), by a
 * fall-through from a warm line (F), or behind a cold line W itself entered by a jal (P), times left by falling into a
 * warm line (S) or by a taken branch at word 0..3 to warm code (B0..B3; B3's slot is the next line's word 0).
 *
 * WHAT IT DOES. seq-miss2's harness: each case its own 8 KB slot, the whole trial in the slot's code (warm-up pass,
 * evictor, spin, timed pass) so only C (and W for P) is cold in the timed pass; warm stubs reset and read Timer 2; W
 * +1F0h, C +200h, D +210h, the branch target X +300h; evictors 4 KB above. 16 trials over the refresh; cold against warm:
${caseList}
 *
 * READ IT LIKE THIS. cold - warm by row: a column that moves with the exit and not the entry is the exit's; a row that
 * moves with P is the pipelined fill's.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js miss-grid\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/miss-grid\\n");
    printf("One cold line by its entry and its exit (Timer 2 cycles, fastest..slowest of 16; cold / warm).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span c = run(trials[i], 1), w = run(trials[i], 0);
        printf("  %-62s cold %3u..%-3u  warm %3u..%-3u  miss %d\\n", names[i], (unsigned)c.lo, (unsigned)c.hi, (unsigned)w.lo, (unsigned)w.hi, (int)c.lo - (int)w.lo);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
