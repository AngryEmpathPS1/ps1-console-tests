/*
 * gpu/gpu-a0poll2 - a poll loop's cost to a GPU upload when the CPU USES its reads' values: gpu-a0mode's compiled loop instruction for
 * instruction (mode X), the same with the Timer 2 value never used (Y), and gpu-a0poll's mode S with each value used two instructions on, as soon as a load allows (U), each
 * with 0-12 nops more, on SyncMode 1 uploads of 4-, 8- and 16-word blocks (2026-11-04, for the SCPH-5501). Written by
 * experiments/mka0poll2.js.
 *
 * WHY. hwtests/gpu-a0poll on the second SCPH-5501: Timer 2 and CHCR2 reads 8 instructions apart cost a 4-word upload nothing at every
 * loop length its sweep made, where gpu-a0mode's compiled loop - the same two reads 8 apart, 22 instructions - reads it ~240 cycles
 * slow. gpu-a0poll's loops never use the Timer 2 value and use CHCR2's late; gpu-a0mode's uses them 2 and 4 instructions on. If the
 * console's CPU runs past an I/O read held by a DMA block until it needs the value (as v0.377.88 found for RAM loads), the two loops run
 * at different periods against the blocks. This emulator holds the CPU for an I/O read's whole wait.
 *
 * WHAT IT DOES. gpu-a0poll's set-up (2,048 words into 1,024x4 at (0,256), vblank's first hblank edge + 500 cycles), then one asm
 * block: a Timer 2 read, CHCR2's store, the loop (one copy per mode and n, entered through a jump table), the last Timer 2 read.
 * Twice each.
 *
 * READ IT LIKE THIS. Q kind mode n rep t turns sum: t the cycles from before the store to after the loop; turns the loop's turns; sum
 * (mode X, Y) the loop's own Timer 2 sum, as gpu-a0mode prints it. No assertions - compare against your emulator.
 */
