static void one(int a, char mode, uint32_t n, int rep) {
    gpuIdle();
    write32(GP1, 0x01000000u);
    write32(GP0, 0x02000000u); write32(GP0, (256u << 16) | 0u); write32(GP0, (4u << 16) | 1024u);
    gpuIdle();
    write32(GP1, 0x04000002u);
    write32(GP0, 0xA0000000u); write32(GP0, (256u << 16) | 0u); write32(GP0, (4u << 16) | 1024u);
    write32(MADR2, (uint32_t)buf & 0xFFFFFCu);
    write32(BCR2, ((uint32_t)(WORDS / a) << 16) | (uint32_t)a);
    toPlace();
    const uint32_t k = (mode == 'X' ? 0 : mode == 'Y' ? 1 : 2) * (NMAX + 1) + n;
    const R r = poll(0x01000201u, k);
    if (read32(CHCR2) & 0x01000000u) write32(CHCR2, 0);
    waitT2(3000);
    uint32_t left = 0;
    while (!(read32(GP1) & (1u << 26)) && left < 8192) { write32(GP0, 0); left++; for (volatile int i = 0; i < 8; i++) {} }
    if (left >= 8192) write32(GP1, 0x01000000u);
    write32(GP1, 0x04000000u);
    printf("Q S%d %c %u %d %u %u %u\n", a, mode, (unsigned)n, rep, (unsigned)r.t, (unsigned)r.turns, (unsigned)r.sum);
}

int main() {
    printf("\ngpu/gpu-a0poll2\n");
    printf("Q kind mode n rep t turns sum (2,048 words into 1,024x4 at (0,256) in vblank; X gpu-a0mode's loop, Y its Timer 2 value unused, U reads used as soon as a load allows; n nops). No assertions.\n\n");
    for (int i = 0; i < WORDS; i++) buf[i] = ((uint32_t)(i + 1) << 16) | (uint32_t)(i + 1);
    EnterCriticalSection();
    const uint16_t m1 = read16(T1_MODE), m2 = read16(T2_MODE);
    write16(T1_MODE, 0x0100);
    write16(T2_MODE, 0);
    write32(DPCR, read32(DPCR) | 0x00000800u);
    write32(GP0, 0xE1000400u); write32(GP0, 0xE2000000u); write32(GP0, 0xE3000000u);
    write32(GP0, 0xE4000000u | (511u << 10) | 1023u); write32(GP0, 0xE5000000u); write32(GP0, 0xE6000000u);
    one(4, 'X', 0, 0);   /* cache the code */
    static const int A[3] = { 4, 8, 16 };
    static const char M[3] = { 'X', 'Y', 'U' };
    for (int k = 0; k < 3; k++) for (int m = 0; m < 3; m++) for (uint32_t n = 0; n <= NMAX; n++) for (int r = 0; r < 2; r++) one(A[k], M[m], n, r);
    gpuIdle();
    write16(T1_MODE, m1);
    write16(T2_MODE, m2);
    write32(I_STAT, ~1u);
    ExitCriticalSection();
    printf("\ngpu/gpu-a0poll2: Done.\n");
    for (;;) VSync(0);
}
