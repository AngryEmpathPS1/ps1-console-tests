'use strict';
// Writes hwtests/store-stall/main.cpp: node hwtests/store-stall/gen.js
const fs = require('fs'), path = require('path');
// t9 = 1F800000h; t1 = the value stored (the register's own value, read before the timed pass, or a target).
// The count starts at a WARM counter reset (the w16 stub); C (entered at word 0 by a jal) holds the store at word 0 and
// runs into warm D; the closing read is the warm stub's. Does a store still pending when the stream ends hide its stall?
const STORES = [
  ['N', 'no store (a nop)', 'nop', null],
  ['T0', 'Timer 0 target', 'sh $t1, 0x1108($t9)', 0x1108],
  ['T1', 'Timer 1 target', 'sh $t1, 0x1118($t9)', 0x1118],
  ['IM', 'I_MASK, its own value', 'sh $t1, 0x1074($t9)', 0x1074],
  ['DP', 'DPCR, its own value', 'sw $t1, 0x10f0($t9)', 0x10f0],
  ['RM', 'RAM word (the slot\'s own)', 'sw $t1, 0x40($t6)', -1],
];
const CASES = [];
for (const [k, w, st, reg] of STORES) {
  CASES.push([`${k}-S`, `${w} at word 0, then nops`, [st, 'nop', 'nop', 'nop'], reg]);
  CASES.push([`${k}-L`, `${w} at word 0, JOY_STAT lbu at word 1`, [st, 'lbu $t0, 0x1044($t9)', 'nop', 'nop'], reg]);
  CASES.push([`${k}-3`, `${w} at word 3`, ['nop', 'nop', 'nop', st], reg]);
}
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw, reg], i) => {
  const b = 'ssB' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  // a0 = evict?, a1 = spin turns; t9 = 1F800000h, t6 = this slot; t1 = the stored value; the count in v0
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`la $t6, ${b}_trial`);
  if (reg === 0x10f0) asm += q('lw $t1, 0x10f0($t9)');
  else if (reg === 0x1074) asm += q('lhu $t1, 0x1074($t9)');
  else if (reg === -1) asm += q('lw $t1, 0x40($t6)');
  else asm += q('li $t1, 0xffff');
  asm += q(`jal ${b}_entry`) + q('nop');
  asm += q(`beqz $a0, ${b}_sp`) + q('nop') + q(`jal ${b}_ev`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_c`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  // C at +0x200, D at +0x210 warm (nops, jr ra)
  asm += q(`.org ${b}_trial + 0x200`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  asm += q('nop') + q('nop') + q('nop') + q('nop') + q('jr $ra') + q('nop') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x1200`) + q(`${b}_ev:`) + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t ssB${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `ssB${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '    ').slice(0, 4)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '     ').slice(0, 5)}${w}`).join('\n');

const src = `/*
 * cpu/store-stall - a store in a streaming line: does it hide the stream's closing stall? (2026-10-12)
 *
 * WHY. hwtests/st-land (SCPH-1001 x3): a Timer 2 counter reset written from a cold line leaves the window as from warm
 * code - the stream's closing stall (the fixup, a streamed load's 2 cycles) not in it. hwtests/hold-read: a read right
 * behind any on-die store - a timer's, I_MASK, DPCR - waits a cycle, cold or warm alike, and never goes around a store held
 * in the stream; so the counter reset's late landing is not reads going around it. Here the count starts at a warm reset
 * and C holds another store - none, Timer 0's or Timer 1's target, I_MASK or DPCR (their own values), a RAM word - at word
 * 0 (then nops, or a JOY_STAT load) or word 3: if a store still pending when the stream ends hides its stall, these rows
 * read under the no-store row.
 *
 * WHAT IT DOES. fix-shadow's harness. 16 trials over the refresh, cold against warm:
${caseList}
 *
 * READ IT LIKE THIS. Each store's row against the N row of the same shape (5 for S and 3, 5 with the load): equal - the
 * store hides nothing; under - it hides the stall.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js store-stall\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t, uint32_t evict) {
    Span s = { 0xFFFF, 0 };
    t(evict, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(evict, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/store-stall\\n");
    printf("A store in a streaming line and the stream's closing stall (Timer 2 cycles, fastest..slowest of 16; cold / warm).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    const uint16_t t0t = read16(0x1F801108u), t1t = read16(0x1F801118u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span c = run(trials[i], 1), w = run(trials[i], 0);
        printf("  %-56s cold %3u..%-3u  warm %3u..%-3u  miss %d\\n", names[i], (unsigned)c.lo, (unsigned)c.hi, (unsigned)w.lo, (unsigned)w.hi, (int)c.lo - (int)w.lo);
    }
    write16(0x1F801108u, t0t);
    write16(0x1F801118u, t1t);
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp');
