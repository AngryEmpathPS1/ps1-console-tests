'use strict';
// Writes hwtests/sw-ioread2/main.cpp: node hwtests/sw-ioread2/gen.js
const fs = require('fs'), path = require('path');
// All warm. sw-ioread's question carried further: four words of stores (or nops), g nops, a JOY_STAT lbu into t0, k nops,
// its reader (x: a nop in the reader's place). The four words: N four nops; R three nops and a RAM store (sw-ioread's
// shape); D a RAM store, two nops, a RAM store - gpu/line-split's loop tail (sw, slti, bnez, sw), whose Timer 1 read
// comes five instructions after its second store with the reader second behind it.
const PRE = {
  N: ['nop', 'nop', 'nop', 'nop'],
  R: ['nop', 'nop', 'nop', 'sw $t1, 0x40($t6)'],
  D: ['sw $t1, 0x40($t6)', 'nop', 'nop', 'sw $t1, 0x44($t6)'],
};
const WHAT = { N: 'no store', R: 'RAM sw', D: 'two RAM sw' };
const CASES = [];
const add = (sk, g, k, reader = true) => {
  const words = [...PRE[sk]];
  for (let j = 0; j < g; j++) words.push('nop');
  words.push('lbu $t0, 0x1044($t9)');
  for (let j = 0; j < k; j++) words.push('nop');
  words.push(reader ? 'addu $t2, $t0, $zero' : 'nop');
  CASES.push([`${sk}${g}${reader ? 'r' : 'x'}${k}`, `${WHAT[sk]}, ${g} nop${g === 1 ? '' : 's'}, JOY_STAT lbu, ${k} nops, ${reader ? 'its reader' : 'no reader'}`, words]);
};
for (const sk of ['N', 'R']) for (const g of [0, 1, 2]) for (const k of [1, 3, 4, 5, 7]) add(sk, g, k);
for (const sk of ['N', 'R', 'D']) for (const g of [3, 5, 7]) for (const k of [1, 3]) add(sk, g, k);
for (const g of [0, 2]) for (const k of [1, 3]) add('D', g, k);
for (const sk of ['N', 'R', 'D']) for (const g of [0, 5]) add(sk, g, 1, false);
const NL = '\\n';
const q = (s) => `    "${s}${NL}"\n`;
let asm = q('.text') + q('.set push') + q('.set noreorder') + q('.set noat');
CASES.forEach(([, , cw], i) => {
  const b = 's2B' + i;
  asm += q('.balign 8192') + q(`.global ${b}_trial`) + q(`${b}_trial:`);
  asm += q('move $t7, $ra') + q('lui $t9, 0x1f80') + q(`la $t6, ${b}_trial`) + q('lw $t1, 0x40($t6)');
  asm += q(`jal ${b}_entry`) + q('nop');
  asm += q(`${b}_sp:`) + q(`bnez $a1, ${b}_sp`) + q('addiu $a1, $a1, -1');
  asm += q(`jal ${b}_entry`) + q('nop') + q('jr $t7') + q('nop');
  asm += q(`.org ${b}_trial + 0x80`) + q(`${b}_w16:`) + q('sh $zero, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`${b}_r16:`) + q('lhu $t3, 0x1120($t9)') + q('jr $ra') + q('nop') + q('nop');
  asm += q(`.org ${b}_trial + 0x100`) + q(`${b}_entry:`);
  asm += q('move $t8, $ra') + q(`jal ${b}_w16`) + q('nop') + q('nop');
  asm += q(`jal ${b}_c`) + q('nop') + q(`jal ${b}_r16`) + q('nop') + q('andi $v0, $t3, 0xffff') + q('jr $t8') + q('nop');
  asm += q(`.org ${b}_trial + 0x200`) + q(`${b}_c:`);
  for (const w of cw) asm += q(w);
  asm += q('nop') + q('nop') + q('nop') + q('jr $ra') + q('nop') + q('nop') + q('nop');
});
asm += q('.balign 8192') + q('nop') + q('.set pop');

const decl = CASES.map((_, i) => `extern "C" uint32_t s2B${i}_trial(uint32_t evict, uint32_t spin);`).join('\n');
const tab = CASES.map((_, i) => `s2B${i}_trial`).join(', ');
const names = CASES.map(([n, w]) => `"${(n + '     ').slice(0, 5)} ${w}"`).join(',\n    ');
const caseList = CASES.map(([n, w]) => ` *   ${(n + '      ').slice(0, 6)}${w}`).join('\n');

const src = `/*
 * cpu/sw-ioread2 - sw-ioread carried further: how long an on-die read behind RAM stores owes its reader, by the reader's
 * distance, the stores' distance and their number (2026-10-12)
 *
 * WHY. hwtests/sw-ioread (SCPH-1001 x3): behind a RAM store, a JOY_STAT read whose value nobody reads costs the CPU nothing;
 * a reader 2-4 instructions on pays 2. A model of exactly that (the read's access waits for the write queue, a reader at
 * positions 2-4 pays the wait less a cycle) read sw-ioread and hold-read but moved gpu/line-split's consensus rows far
 * (56 exact 1,791 inside 290 out -> 0 / 1,227 / 854): line-split's Timer 1 read comes five instructions after TWO RAM
 * stores, its reader second. Here the reader at 2, 4, 5, 6 and 8 instructions behind the read (k nops, k = 1 3 4 5 7),
 * 0-7 nops between the stores and the read, one store or line-split's two, and a nop in the reader's place.
 *
 * WHAT IT DOES. All warm, sw-ioread's harness. 16 trials over the refresh:
${caseList}
 *
 * READ IT LIKE THIS. R or D against N at the same g and k: what the reader pays for the stores; an x row against N's:
 * what the CPU pays with no reader.
 *
 * There are no assertions - compare against your emulator.
 *
 * THE RULE: run it here first: \`node hwtests/run.js sw-ioread2\`. Generated by gen.js.
 */
#include <common.h>
#include <psxapi.h>
#include <io.h>

${decl}
__asm__(
${asm});

typedef uint32_t (*Trial)(uint32_t, uint32_t);
static const Trial trials[] = { ${tab} };
static const char* const names[] = {
    ${names}
};
struct Span { uint32_t lo, hi; };
static Span run(Trial t) {
    Span s = { 0xFFFF, 0 };
    t(0, 0);
    for (uint32_t k = 0; k < 16; k++) {
        const uint32_t v = t(0, k * 8);
        if (v < s.lo) s.lo = v;
        if (v > s.hi) s.hi = v;
    }
    return s;
}

int main() {
    printf("\\ncpu/sw-ioread2\\n");
    printf("An on-die read behind RAM stores and its reader, warm code (Timer 2 cycles, fastest..slowest of 16).\\n");
    printf("There are no assertions - compare against your emulator.\\n\\n");
    EnterCriticalSection();
    const uint16_t m2 = read16(0x1F801124u);
    write16(0x1F801124u, 0);
    for (unsigned i = 0; i < sizeof(trials) / sizeof(trials[0]); i++) {
        const Span w = run(trials[i]);
        printf("  %-58s cold %3u..%-3u  warm %3u..%-3u  miss 0\\n", names[i], (unsigned)w.lo, (unsigned)w.hi, (unsigned)w.lo, (unsigned)w.hi);
    }
    write16(0x1F801124u, m2);
    ExitCriticalSection();
    printf("\\nDone.\\n");
    for (;;) {}   /* park after Done. (console day: a program that returns leaves Unirom deaf) */
}
`;
fs.writeFileSync(path.join(__dirname, 'main.cpp'), src);
console.log('wrote main.cpp, ' + CASES.length + ' cases');
